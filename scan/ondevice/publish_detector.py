#!/usr/bin/env python3
"""Explicitly publish an already reviewed detector; regenerate coherent pins.

Run after native/copy/rule changes and before tests/build. Source weights and
review data stay outside git. The existing resource filename is intentional.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parents[2]
from export_detector import VOCABULARY, sha


def tree_sha(path):
    digest = hashlib.sha256()
    for file in sorted(path.rglob("*")):
        if file.is_file():
            digest.update(file.relative_to(path).as_posix().encode() + b"\0" + bytes.fromhex(sha(file)))
    return digest.hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--export-dir", type=Path, required=True)
    args = parser.parse_args()
    meta = json.loads((args.export_dir / "export.json").read_text())
    if meta["vocabulary"] != VOCABULARY:
        raise ValueError("Export vocabulary differs; export and review again before publishing.")
    rules = json.loads(Path(__file__).with_name("detector-rules.json").read_text())
    dest = ROOT / "ios/App/App/HazardModel"
    package = dest / "HazardImageEncoder.mlpackage"
    source = args.export_dir / meta["package"]
    if source.resolve() != package.resolve():
        shutil.copytree(source, package, dirs_exist_ok=True)
    weight = package / "Data/com.apple.CoreML/weights/weight.bin"
    sources = ["ios/App/App/FixListHazardsPlugin.swift", "src/lib/ondevice-contract.ts",
               "src/lib/ondevice-flags.ts", "src/lib/capture-suggestions.ts",
               "src/lib/capture-storage.ts", "src/lib/capture-types.ts",
               "scan/ondevice/detector-rules.json", "scan/hazard-questions.json"]
    runtime = hashlib.sha256(bytes.fromhex(tree_sha(package)))
    for name in sources:
        runtime.update(name.encode() + b"\0" + bytes.fromhex(sha(ROOT / name)))
    model = {"name": "YOLO-World-v2-small/fixlist-visible-objects-v1", "backend": "coreml",
             "engine": "yolo-world-object-rules", "license": "AGPL-3.0 weights and runtime",
             "identity": {"version": 1, "weightsSHA256": meta["sourceSHA256"], "runtimeSHA256": runtime.hexdigest()}}
    manifest = {**rules, "model": model, "classes": VOCABULARY, "packageSHA256": tree_sha(package),
                "weight": {"bytes": weight.stat().st_size, "sha256": sha(weight)},
                "export": meta, "runtimeSources": {p: sha(ROOT / p) for p in sources}}
    (dest / "hazard-prompts.json").write_text(json.dumps(manifest, indent=2) + "\n")
    thresholds = {i["checklistItemId"]: i["threshold"] for i in rules["items"]}
    (ROOT / "src/lib/ondevice-model.ts").write_text(
        '/** Generated by scan/ondevice/publish_detector.py. Uncalibrated object proposals. */\n'
        + 'export const ONDEVICE_MODEL = ' + json.dumps(model, indent=2) + ' as const;\n'
        + 'export const ONDEVICE_THRESHOLDS: Readonly<Record<string, number>> = ' + json.dumps(thresholds, indent=2) + ';\n'
        + '/** Box centres are supported by the fired rule, without the old CLIP 0.7 gate. */\n'
        + 'export const ONDEVICE_LOCATION_THRESHOLD = 0;\n'
        + 'export const ONDEVICE_LIMITATION = "Unverified AI output: possible visible objects for you to review, not a safety verdict. Confidence is not hazard probability. Lower-frame position does not prove an object is on the floor. Missed detections do not mean the area is safe; no grab bar detected does not mean none exists. You decide what needs attention.";\n')
    verifier = ROOT / "scripts/verify-ios-model.sh"
    source = verifier.read_text()
    source = re.sub(r"(?m)^expected_bytes=\d+$", f"expected_bytes={weight.stat().st_size}", source)
    source = re.sub(r"(?m)^expected_sha256=[a-f0-9]{64}$", f"expected_sha256={sha(weight)}", source)
    verifier.write_text(source)
    print(json.dumps({"model": model, "packageBytes": sum(f.stat().st_size for f in package.rglob('*') if f.is_file()),
                      "weightBytes": weight.stat().st_size, "weightSHA256": sha(weight)}, indent=2))


if __name__ == "__main__":
    main()
